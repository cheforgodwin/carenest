import { parse } from '@babel/parser'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = process.cwd()
const sourceRoots = ['src/pages', 'src/components', 'src/auth', 'src/config', 'src/firebase']
const attributeNames = new Set(['placeholder', 'title', 'aria-label'])
const ignored = new Set(['Care', 'CareNest', 'Escape', 'Nest', 'checkbox', 'email', 'number', 'password', 'submit', 'tel', 'text'])

async function sourceFiles(directory) {
  const entries = await readdir(path.join(root, directory), { withFileTypes: true })
  const nested = await Promise.all(entries.map((entry) => {
    const relative = path.join(directory, entry.name)
    return entry.isDirectory() ? sourceFiles(relative) : relative
  }))
  return nested.flat().filter((file) => /\.[jt]sx?$/.test(file))
}

function clean(value) {
  return String(value || '').replace(/\s+/g, ' ').trim()
}

function looksVisible(value) {
  const text = clean(value)
  if (!text || ignored.has(text) || !/[A-Za-z]/.test(text)) return false
  if (/^(\.|\/|#|https?:|tel:)/.test(text)) return false
  if (/^[a-z][A-Za-z\d-]*$/.test(text) && !['account', 'customer', 'provider', 'rider'].includes(text)) return false
  if (/\b[a-z]+-[a-z-]+\b/.test(text) || (/\./.test(text) && !/\s/.test(text))) return false
  if (/^[\w.+-]+\/[\w.+-]+$/.test(text)) return false
  if (/^[\w-]+\.(jsx?|css)$/.test(text)) return false
  return true
}

function addLiteral(node, values) {
  if (!node) return
  if (node.type === 'StringLiteral' && looksVisible(node.value)) values.add(clean(node.value))
  if (node.type === 'ConditionalExpression') {
    addLiteral(node.consequent, values)
    addLiteral(node.alternate, values)
  }
  if (node.type === 'LogicalExpression') {
    addLiteral(node.left, values)
    addLiteral(node.right, values)
  }
  if (node.type === 'ArrayExpression') node.elements.forEach((item) => addLiteral(item, values))
  if (node.type === 'ObjectExpression') node.properties.forEach((property) => addLiteral(property.value, values))
}

function visit(node, values) {
  if (!node || typeof node !== 'object') return
  if (node.type === 'JSXText' && looksVisible(node.value)) values.add(clean(node.value))
  if (node.type === 'JSXAttribute' && attributeNames.has(node.name?.name)) {
    if (node.value?.type === 'StringLiteral' && looksVisible(node.value.value)) values.add(clean(node.value.value))
    if (node.value?.type === 'JSXExpressionContainer') addLiteral(node.value.expression, values)
  }
  if (node.type === 'JSXExpressionContainer') addLiteral(node.expression, values)
  if (node.type === 'VariableDeclarator') addLiteral(node.init, values)
  for (const [key, child] of Object.entries(node)) {
    if (['loc', 'start', 'end', 'extra'].includes(key)) continue
    if (Array.isArray(child)) child.forEach((item) => visit(item, values))
    else if (child && typeof child === 'object') visit(child, values)
  }
}

const values = new Set()
for (const file of (await Promise.all(sourceRoots.map(sourceFiles))).flat()) {
  const source = await readFile(path.join(root, file), 'utf8')
  const ast = parse(source, { sourceType: 'module', plugins: ['jsx'] })
  visit(ast, values)
}

const catalog = [...values].sort((left, right) => left.localeCompare(right))
const output = `// Generated by scripts/generate-ui-catalog.mjs. Do not edit manually.\nexport const uiEnglishText = ${JSON.stringify(catalog, null, 2)}\n`
await writeFile(path.join(root, 'src/i18n/uiTextCatalog.js'), output)
console.log(`Generated ${catalog.length} translatable UI strings.`)
